#!/usr/bin/env python3
"""Build data/verbs.js from Fred Jehle's Spanish verb database.

Source: https://github.com/ghidinelli/fred-jehle-spanish-verbs
License: CC BY-NC-SA 3.0

Usage: python3 scripts/build_verbs.py
"""
import csv
import io
import json
import pathlib
import urllib.request

SRC = "https://raw.githubusercontent.com/ghidinelli/fred-jehle-spanish-verbs/master/jehle_verb_database.csv"
OUT = pathlib.Path(__file__).resolve().parent.parent / "data" / "verbs.js"

# (mood_english, tense_english) -> key used in the app
TENSES = {
    ("Indicative", "Present"): "present",
}
FORMS = ["form_1s", "form_2s", "form_3s", "form_1p", "form_2p", "form_3p"]


def group_of(infinitive):
    stem = infinitive[:-2] if infinitive.endswith("se") else infinitive
    return {"ar": "ar", "er": "er", "ir": "ir", "ír": "ir"}[stem[-2:]]


def main():
    raw = urllib.request.urlopen(SRC).read().decode("utf-8")
    verbs = {}
    for row in csv.DictReader(io.StringIO(raw)):
        key = TENSES.get((row["mood_english"], row["tense_english"]))
        if not key:
            continue
        inf = row["infinitive"]
        v = verbs.setdefault(inf, {
            "inf": inf,
            "en": row["infinitive_english"],
            "group": group_of(inf),
            "tenses": {},
        })
        # Empty string where a form doesn't exist (e.g. llover)
        v["tenses"][key] = [row[f] for f in FORMS]

    data = sorted(verbs.values(), key=lambda v: v["inf"])
    OUT.write_text(
        "// Generated by scripts/build_verbs.py — do not edit.\n"
        "// Data: Fred Jehle Spanish verb database, CC BY-NC-SA 3.0\n"
        "window.VERBS = " + json.dumps(data, ensure_ascii=False, separators=(",", ":")) + ";\n",
        encoding="utf-8",
    )
    print(f"{len(data)} verbs -> {OUT}")


if __name__ == "__main__":
    main()
