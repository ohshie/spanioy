#!/usr/bin/env python3
"""Build data/sentences.js from Tatoeba English-Spanish sentence pairs.

Source: https://tatoeba.org/en/downloads (per-language exports)
License: CC BY 2.0 FR

Usage: python3 scripts/build_sentences.py
"""
import bz2
import collections
import json
import pathlib
import random
import re
import urllib.request

BASE = "https://downloads.tatoeba.org/exports/per_language/"
OUT = pathlib.Path(__file__).resolve().parent.parent / "data" / "sentences.js"

PER_TOPIC = 500
MAX_WORDS = 6
TOPICS = {
    "tener": re.compile(r"\b(tengo|tienes|tiene|tenemos|tenéis|tienen)\b"),
    "se": re.compile(r"\bse\b"),
    "de": re.compile(r"\b(de|del)\b"),
}


def rows(path):
    print("fetching", path)
    data = bz2.decompress(urllib.request.urlopen(BASE + path).read()).decode("utf-8")
    for line in data.splitlines():
        yield line.split("\t")


# Plain sentences only: no quotes, digits or letters outside English/Spanish
EN_OK = re.compile(r"^[A-Za-z' ,.?!-]+$")
ES_OK = re.compile(r"^[A-Za-záéíóúüñÁÉÍÓÚÜÑ¿¡ ,.?!-]+$")
# Sentences about languages / spelling are not useful drills
META = re.compile(r"\b(esperanto|word|letter|spell|translate|sentence|tatoeba)\b", re.I)


def words(s):
    return re.findall(r"[\wáéíóúñü']+", s.lower())


def main():
    spa = {r[0]: r[2] for r in rows("spa/spa_sentences.tsv.bz2")}
    links = [(s, e) for s, e in rows("spa/spa-eng_links.tsv.bz2")]
    linked = {e for _, e in links}
    eng = {r[0]: r[2] for r in rows("eng/eng_sentences.tsv.bz2") if r[0] in linked}

    # Every Spanish translation of an English sentence is an accepted answer
    by_en = collections.defaultdict(set)
    for s, e in links:
        if s in spa and e in eng:
            by_en[eng[e]].add(spa[s])

    candidates = collections.defaultdict(list)
    for en, es in list(by_en.items()):
        es = {x for x in es if ES_OK.match(x)}
        if len(words(en)) > MAX_WORDS or not EN_OK.match(en) or META.search(en) or not es:
            continue
        by_en[en] = es
        for topic, rx in TOPICS.items():
            if any(rx.search(x.lower()) and len(words(x)) <= MAX_WORDS for x in es):
                candidates[topic].append(en)

    rng = random.Random(42)
    chosen = set()
    for topic in TOPICS:
        pool = sorted(candidates[topic])
        chosen.update(rng.sample(pool, min(PER_TOPIC, len(pool))))

    data = []
    for en in sorted(chosen):
        es = sorted(by_en[en])
        topics = [t for t, rx in TOPICS.items() if any(rx.search(x.lower()) for x in es)]
        # Answer shown on a mistake: shortest translation that uses a topic word
        main_es = min((x for x in es if any(TOPICS[t].search(x.lower()) for t in topics)), key=len)
        data.append({"en": en, "es": [main_es] + [x for x in es if x != main_es], "topics": topics})

    OUT.write_text(
        "// Generated by scripts/build_sentences.py — do not edit.\n"
        "// Data: Tatoeba (tatoeba.org), CC BY 2.0 FR\n"
        "window.SENTENCES = " + json.dumps(data, ensure_ascii=False, separators=(",", ":")) + ";\n",
        encoding="utf-8",
    )
    counts = collections.Counter(t for d in data for t in d["topics"])
    print(f"{len(data)} sentences {dict(counts)} -> {OUT}")


if __name__ == "__main__":
    main()
