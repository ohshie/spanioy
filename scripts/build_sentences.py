#!/usr/bin/env python3
"""Build data/sentences.js from Tatoeba English-Spanish sentence pairs.

Sentences: https://tatoeba.org/en/downloads (per-language exports), CC BY 2.0 FR
Word frequency (for levels): https://github.com/hermitdave/FrequencyWords
  (OpenSubtitles 2018, es_50k), CC BY-SA 4.0

Level = rank of the rarest word in the Spanish sentence (names ignored):
  0: all words in the top 150, 1: top 500, 2: top 1500, 3: top 5000. Rarer sentences are dropped.

Usage: python3 scripts/build_sentences.py
"""
import bz2
import collections
import json
import pathlib
import random
import re
import urllib.request

BASE = "https://downloads.tatoeba.org/exports/per_language/"
FREQ = "https://raw.githubusercontent.com/hermitdave/FrequencyWords/master/content/2018/es/es_50k.txt"
OUT = pathlib.Path(__file__).resolve().parent.parent / "data" / "sentences.js"

PER_TOPIC_LEVEL = 200
MAX_WORDS = 6
LEVELS = [(0, 150), (1, 500), (2, 1500), (3, 5000)]
TOPICS = {
    "tener": re.compile(r"\b(tengo|tienes|tiene|tenemos|tenéis|tienen)\b"),
    "se": re.compile(r"\bse\b"),
    "de": re.compile(r"\b(de|del)\b"),
}

# Plain sentences only: no quotes, digits or letters outside English/Spanish
EN_OK = re.compile(r"^[A-Za-z' ,.?!-]+$")
ES_OK = re.compile(r"^[A-Za-záéíóúüñÁÉÍÓÚÜÑ¿¡ ,.?!-]+$")
# Sentences about languages / spelling are not useful drills
META = re.compile(r"\b(esperanto|word|letter|spell|translate|sentence|tatoeba)\b", re.I)


def fetch(url):
    print("fetching", url)
    return urllib.request.urlopen(url).read()


def rows(path):
    for line in bz2.decompress(fetch(BASE + path)).decode("utf-8").splitlines():
        yield line.split("\t")


def words(s):
    return re.findall(r"[\wáéíóúñü']+", s.lower())


def main():
    rank = {}
    for i, line in enumerate(fetch(FREQ).decode("utf-8").splitlines()):
        rank.setdefault(line.split(" ")[0], i + 1)

    def level(es):
        tokens = re.findall(r"[\wáéíóúüñÁÉÍÓÚÜÑ]+", es)
        # Capitalised words after the first are names
        hardest = max((rank.get(t.lower(), 10**9) for k, t in enumerate(tokens) if k == 0 or not t[0].isupper()), default=0)
        return next((lv for lv, top in LEVELS if hardest <= top), None)

    spa = {r[0]: r[2] for r in rows("spa/spa_sentences.tsv.bz2")}
    links = [(s, e) for s, e in rows("spa/spa-eng_links.tsv.bz2")]
    linked = {e for _, e in links}
    eng = {r[0]: r[2] for r in rows("eng/eng_sentences.tsv.bz2") if r[0] in linked}

    # Every Spanish translation of an English sentence is an accepted answer
    by_en = collections.defaultdict(set)
    for s, e in links:
        if s in spa and e in eng:
            by_en[eng[e]].add(spa[s])

    items = {}
    candidates = collections.defaultdict(list)
    for en, es in by_en.items():
        es = sorted(x for x in es if ES_OK.match(x))
        if len(words(en)) > MAX_WORDS or not EN_OK.match(en) or META.search(en) or not es:
            continue
        # Main answer: easiest short translation that uses a topic word
        rated = [(level(x), len(x), x) for x in es
                 if len(words(x)) <= MAX_WORDS and any(rx.search(x.lower()) for rx in TOPICS.values())]
        rated = [r for r in rated if r[0] is not None]
        if not rated:
            continue
        lv, _, main_es = min(rated)
        topics = [t for t, rx in TOPICS.items() if rx.search(main_es.lower())]
        items[en] = {"en": en, "es": [main_es] + [x for x in es if x != main_es], "topics": topics, "level": lv}
        for t in topics:
            candidates[(t, lv)].append(en)

    rng = random.Random(42)
    chosen = set()
    for key in sorted(candidates):
        pool = sorted(candidates[key])
        chosen.update(rng.sample(pool, min(PER_TOPIC_LEVEL, len(pool))))

    data = [items[en] for en in sorted(chosen)]
    OUT.write_text(
        "// Generated by scripts/build_sentences.py — do not edit.\n"
        "// Data: Tatoeba (tatoeba.org), CC BY 2.0 FR. Levels: FrequencyWords (OpenSubtitles 2018), CC BY-SA 4.0\n"
        "window.SENTENCES = " + json.dumps(data, ensure_ascii=False, separators=(",", ":")) + ";\n",
        encoding="utf-8",
    )
    counts = collections.Counter((t, d["level"]) for d in data for t in d["topics"])
    print(f"{len(data)} sentences {dict(sorted(counts.items()))} -> {OUT}")


if __name__ == "__main__":
    main()
